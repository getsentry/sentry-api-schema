/** Generate the standalone, data-only operation catalog from the same release inputs. */
import { readFileSync, writeFileSync, copyFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { extractOperations } from "../lib/operation-catalog.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const spec = JSON.parse(readFileSync(join(root, "openapi-derefed.json"), "utf8"));
const source = readFileSync(join(root, "src", "sdk.gen.ts"), "utf8");
const operations = extractOperations(spec, source);
copyFileSync(join(root, "lib", "operation-types.ts"), join(root, "src", "operation-types.ts"));
writeFileSync(join(root, "src", "operations.ts"), [
  "// This file is auto-generated by scripts/generate-operations.mjs.",
  "import type { ApiOperation } from './operation-types.ts';",
  "export type { ApiOperation, ApiQueryParameter } from './operation-types.ts';",
  "",
  "/** Offline metadata for the operations exported by this SDK version. */",
  `export const operations: readonly ApiOperation[] = ${JSON.stringify(operations, null, 2)};`,
  "",
].join("\n"));
